#!/usr/bin/env python3
"""Write the step table that cuevik-start's shell scripts read.

Usage:  python scripts/gen-steps-table.py          write plugins/cuevik-start/scripts/steps.table
        python scripts/gen-steps-table.py --check  fail if that file is stale; write nothing
Needs:  PyYAML
Why:    the plugin's scripts run in bash on the operator's machine, where nothing can read YAML.
        steps.table is steps.yml and express.yml reduced to what bash can split on "|".

Lines
  express|<lane branch>|<covered step ids, space-separated>
  step|<id>|<slug>|<branch>|<alias branches, space-separated, or ->|<primary output>|<file check>
  <file check> is what `status` looks for on main: `bootstrap` (the two .cuevik files), `finalize`
  (CONTRIBUTING.md without its INITIATION-ONLY block), `none` (a replacesExisting step: its output is
  on main before it runs) or `file` (the primary output).
"""
import sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent
START = ROOT / "plugins" / "cuevik-start"
TABLE = START / "scripts" / "steps.table"


def file_check(step):
    if step.get("bootstrap"):
        return "bootstrap"
    if step["slug"] == "finalize":
        return "finalize"
    return "none" if step.get("replacesExisting") else "file"


def render():
    steps = yaml.safe_load((START / "references" / "steps.yml").read_text(encoding="utf-8"))["steps"]
    lane = yaml.safe_load((START / "references" / "express.yml").read_text(encoding="utf-8"))["express"]
    lines = ["# Generated by scripts/gen-steps-table.py from references/steps.yml and references/express.yml.",
             "# Do not edit: change those files and run the generator.",
             f"express|{lane['branch']}|{' '.join(lane['covers'])}"]
    for s in steps:
        aliases = " ".join(f"init/{a}" for a in s.get("aliases", [])) or "-"
        fields = ["step", s["id"], s["slug"], s["branch"], aliases, s["outputs"][0], file_check(s)]
        if bad := [f for f in fields if "|" in f or not f]:
            sys.exit(f"step {s['id']}: a field is empty or holds '|': {bad}")
        lines.append("|".join(fields))
    return "\n".join(lines) + "\n"


def main():
    want = render()
    rel = TABLE.relative_to(ROOT).as_posix()
    if "--check" in sys.argv[1:]:
        have = TABLE.read_bytes().replace(b"\r\n", b"\n").decode("utf-8") if TABLE.is_file() else None
        if have != want:
            sys.exit(f"{rel} is stale. Run: python scripts/gen-steps-table.py")
        print(f"step table is current ({want.count(chr(10)) - 3} steps)")
        return
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {rel}")


if __name__ == "__main__":
    main()
